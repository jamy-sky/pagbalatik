// Builds src/renderer/report.js from the reviewed code in mockups/natal-report-mockup.html, so the app's report
// is the mockup's report. Run it after changing the mockup's tables, wording or pages: node scripts/build-report.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const L = fs.readFileSync(path.join(root, 'mockups/natal-report-mockup.html'), 'utf8').split(/\r?\n/);
const seg = (a, b) => L.slice(a - 1, b).join('\n');
const find = (re) => { const i = L.findIndex((l) => re.test(l)); if (i < 0) throw new Error(`not found in the mockup: ${re}`); return i + 1; };

const hStart = find(/^  const E = window\.ChartEngine;/);
const hEnd = find(/^  const an = \(w\) =>/);
const tStart = find(/^  \/\/ ---------- traditional tables ----------/);
const wStart = find(/^  \/\/ ---------- wheel \(FEMT geometry\) ----------/);
const wordStart = find(/^  \/\/ ---------- wording/);
const scrStart = find(/^  \/\/ ---------- screens ----------/);

const helpers = seg(hStart, hEnd)
  .replace(/^  const \$ = .*$/m, '')
  .replace('const E = window.ChartEngine;', "const E = root.ChartEngine || require('./chart-engine.js');");
let body = seg(tStart, wStart - 1)
  + "\n  // The wheel is shared with the chart view (wheel.js).\n  const wheel = (ch) => (root.Wheel || require('./wheel.js')).svg(ch, null, { modern: S.modern !== 'off' });\n\n"
  + seg(wordStart, scrStart - 1);
if (!body.includes('budget = 842 - base - 4')) throw new Error('the remedy page budget line has moved');
body = body.replace('budget = 842 - base - 4', 'budget = PAGE_H() - base - 4');

const out = `/* Pagbalatik: the natal reading. Analysis (dignity, sect, temperament, lots, timing, remedies), its wording, and
   the report pages as HTML. The pages are what the app previews, prints to PDF, and walks into a DOCX.
   The wording is our own; the rules come from the authors cited under each section.
   GENERATED by scripts/build-report.js from mockups/natal-report-mockup.html: change the mockup, then rebuild. */
(function (root) {
  'use strict';
${helpers}

  // The options of the report being built (Settings and the report's own choices), set by build().
  let S = {};
  const PAGE_H = () => (S.paper === 'letter' ? 792 : 842);
  const fmtBirth = (p) => { const [y, mo, d, h, mi] = p.birth; return \`\${d} \${MONTHS[mo - 1]} \${y}, \${pad(h)}:\${pad(mi)}\`; };
  const offsetOf = (p) => { const o = E.utcToZoned(p.ms, p.tz).offset; return \`UTC\${o < 0 ? '−' : '+'}\${pad(Math.floor(Math.abs(o) / 60))}:\${pad(Math.abs(o) % 60)}\`; };

${body}
  const DEFAULTS = {
    logo: null, logoSize: 34, logoWhere: 'all', practice: '', contact: '', style: 'vellum', paper: 'a4',
    houses: 'whole', trip: 'dorothean', modern: 'listed', omitDeath: true, cite: true, herbs: true,
    sec: { cover: true, glance: true, dignities: true, temperament: true, planets: true, houses: true, lots: true, timing: true, remedies: true, sources: true },
  };
  const withBirth = (person) => { const z = E.utcToZoned(person.ms, person.tz); return { ...person, birth: [z.y, z.m, z.d, z.h, z.mi] }; };
  const setOpts = (opts) => { S = { ...DEFAULTS, ...opts, sec: { ...DEFAULTS.sec, ...(opts && opts.sec) } }; };

  /** person: { name, ms, tz, place: { name, lat, lon } }. opts: see DEFAULTS. Returns { A, pages: [{ id, title, html(n, of) }] }. */
  function build(person, opts) {
    setOpts(opts);
    const A = analyse(withBirth(person));
    return { A, pages: pages(A) };
  }
  const api = {
    build, DEFAULTS, T7, RULER, EXALT, TERMS, FACES, TRIP, AGRIPPA, CULPEPER, ANTIPATHY, FICINO, termLord, faceLord,
    analyse: (person, opts) => { setOpts(opts); return analyse(withBirth(person)); },
    essential: (id, lon, day, opts) => { setOpts(opts); return essential(id, lon, day); },
    remedies: (A, opts) => { setOpts(opts); return remedies(A); },
    temperament: (A) => temperament(A), profections: (A) => profections(A), firdaria: (A) => firdaria(A),
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.Report = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'src/renderer/report.js'), out);
console.log(`  wrote src/renderer/report.js (${out.split('\n').length} lines)`);

// The report pages' styles: the mockup's paper section, as it is.
const cStart = find(/^\/\* ---------- paper ---------- \*\/$/);
const cEnd = L.findIndex((l, i) => i >= cStart && /^@media/.test(l));
const css = `/* Pagbalatik: the report pages (A4 or Letter, 1 px = 1 pt), on screen and in print.
   GENERATED by scripts/build-report.js from mockups/natal-report-mockup.html: change the mockup, then rebuild. */
${L.slice(cStart, cEnd).join('\n')}
.paper.letter { width: 612px; min-height: 792px; }
`;
fs.writeFileSync(path.join(root, 'src/renderer/report.css'), css);
console.log(`  wrote src/renderer/report.css (${css.split('\n').length} lines)`);
